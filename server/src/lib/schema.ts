/**
 * The complete Postgres schema, kept as one idempotent statement block so it
 * can be applied by `migrate()` and exercised directly by the dialect test.
 *
 * Column names mirror the original Laravel migrations. `created_at` /
 * `updated_at` are real `timestamptz` columns that come back out as ISO
 * strings (see the type parsers in `db.ts`); `depart_date` stays `text`
 * because the whole app treats it as a `YYYY-MM-DD` string.
 */
export const SCHEMA_SQL = `
    CREATE TABLE IF NOT EXISTS airports (
      id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      code        text        NOT NULL,
      name        text        NOT NULL,
      city        text        NOT NULL,
      country     text        NOT NULL DEFAULT 'United Kingdom',
      description text        NOT NULL DEFAULT '',
      image       text        NOT NULL DEFAULT '',
      sort_order  integer     NOT NULL DEFAULT 0,
      created_at  timestamptz NOT NULL DEFAULT now(),
      updated_at  timestamptz NOT NULL DEFAULT now()
    );

    CREATE UNIQUE INDEX IF NOT EXISTS airports_code_key ON airports (code);

    CREATE TABLE IF NOT EXISTS vehicles (
      id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name              text             NOT NULL,
      slug              text             NOT NULL UNIQUE,
      price             double precision NOT NULL DEFAULT 0,
      short_base        double precision NOT NULL DEFAULT 0,
      short_per_mile    double precision NOT NULL DEFAULT 0,
      long_base         double precision NOT NULL DEFAULT 0,
      long_per_mile     double precision NOT NULL DEFAULT 0,
      passengers        integer          NOT NULL DEFAULT 1,
      suitcases         integer          NOT NULL DEFAULT 0,
      hand_luggage_note text,
      image             text             NOT NULL DEFAULT '',
      description       text,
      car_model         text,
      sort_order        integer          NOT NULL DEFAULT 0,
      created_at        timestamptz      NOT NULL DEFAULT now(),
      updated_at        timestamptz      NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS faqs (
      id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      question   text        NOT NULL,
      answer     text        NOT NULL,
      sort_order integer     NOT NULL DEFAULT 0,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS bookings (
      id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      reference      text             NOT NULL UNIQUE,
      from_location  text             NOT NULL,
      to_location    text             NOT NULL,
      depart_date    text             NOT NULL,
      depart_time    text,
      vehicle_id     integer          NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
      passenger_name text,
      email          text,
      phone          text,
      country_code   text,
      flight_number  text,
      note_to_driver text,
      passengers     integer          NOT NULL DEFAULT 1,
      suitcases      integer          NOT NULL DEFAULT 0,
      hand_luggage   integer          NOT NULL DEFAULT 0,
      extras         text             NOT NULL DEFAULT '[]',
      distance       text,
      duration       text,
      status         text             NOT NULL DEFAULT 'pending',
      payment_status text             NOT NULL DEFAULT 'unpaid',
      payment_id     text,
      total_price    double precision NOT NULL DEFAULT 0,
      created_at     timestamptz      NOT NULL DEFAULT now(),
      updated_at     timestamptz      NOT NULL DEFAULT now()
    );

    CREATE INDEX IF NOT EXISTS bookings_status_idx     ON bookings (status);
    CREATE INDEX IF NOT EXISTS bookings_payment_idx    ON bookings (payment_status);
    CREATE INDEX IF NOT EXISTS bookings_created_at_idx ON bookings (created_at);

    CREATE TABLE IF NOT EXISTS contact_messages (
      id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name       text        NOT NULL,
      email      text        NOT NULL,
      subject    text,
      message    text        NOT NULL,
      read       boolean     NOT NULL DEFAULT false,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS subscribers (
      id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email      text        NOT NULL UNIQUE,
      name       text,
      active     boolean     NOT NULL DEFAULT true,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS admins (
      id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name       text        NOT NULL,
      email      text        NOT NULL UNIQUE,
      password   text        NOT NULL,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS admin_notifications (
      id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      type       text        NOT NULL,
      message    text        NOT NULL,
      data       text,
      read       boolean     NOT NULL DEFAULT false,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS promotions (
      id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      subject         text        NOT NULL,
      message         text        NOT NULL,
      recipient_count integer     NOT NULL DEFAULT 0,
      sent_count      integer     NOT NULL DEFAULT 0,
      status          text        NOT NULL DEFAULT 'queued',
      created_at      timestamptz NOT NULL DEFAULT now(),
      updated_at      timestamptz NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS zones (
      id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name       text        NOT NULL,
      colour     text        NOT NULL DEFAULT '#f59e0b',
      geometry   text        NOT NULL,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now()
    );
  `;
